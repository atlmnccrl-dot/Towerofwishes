HL.FONT_H = 9; // 7 cap rows + 2 descender rows
const glyphs = {};
for (const ch in GL) {
  const rows = GL[ch].split('/');
  glyphs[ch] = { w: Math.max(...rows.map((r) => r.length)), rows };
}
glyphs[' '] = { w: 3, rows: [] };
const fontCache = {};
function fontAtlas(color) {
  if (fontCache[color]) return fontCache[color];
  const chars = Object.keys(glyphs);
  const c = HL.canvas(chars.length * 6, HL.FONT_H);
  c.g.fillStyle = color;
  const map = {};
  chars.forEach((ch, i) => {
    const gl = glyphs[ch];
    gl.rows.forEach((r, y) => { for (let x = 0; x < r.length; x++) if (r[x] === '#') c.g.fillRect(i * 6 + x, y, 1, 1); });
    map[ch] = i * 6;
  });
  return (fontCache[color] = { c, map });
}
HL.textWidth = (s, scale = 1) => {
  let w = 0;
  for (const ch of String(s)) w += ((glyphs[ch] || glyphs['?']).w + 1);
  return Math.max(0, w - 1) * scale;
};
// align: 0 left, 0.5 centre, 1 right. y = top of cap height.
HL.text = (g, s, x, y, color = '#ebe3d0', align = 0, scale = 1, shadow = null) => {
  s = String(s);
  if (shadow) HL.text(g, s, x + scale, y + scale, shadow, align, scale, null);
  const at = fontAtlas(color);
  let cx = Math.round(x - HL.textWidth(s, scale) * align);
  y = Math.round(y);
  for (const ch of s) {
    const gl = glyphs[ch] || glyphs['?'];
    const sx = at.map[ch in at.map ? ch : '?'];
    if (gl.rows.length) g.drawImage(at.c, sx, 0, gl.w, HL.FONT_H, cx, y, gl.w * scale, HL.FONT_H * scale);
    cx += (gl.w + 1) * scale;
  }
};
// Word wrap into lines no wider than maxW pixels.
HL.wrap = (s, maxW, scale = 1) => {
  const out = [];
  for (const para of String(s).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (HL.textWidth(t, scale) > maxW && line) { out.push(line); line = word; } else line = t;
    }
    out.push(line);
  }
  return out;
};
