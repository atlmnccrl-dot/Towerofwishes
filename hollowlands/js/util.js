// HOLLOWLANDS — shared helpers: math, deterministic noise, canvases, the pixel font.
const HL = (window.HL = {});

HL.BUILD = '0.8.0';
HL.TAU = Math.PI * 2;
HL.clamp = (v, a, b) => (v < a ? a : v > b ? b : v);
HL.lerp = (a, b, t) => a + (b - a) * t;
HL.dist = (ax, ay, bx, by) => Math.hypot(bx - ax, by - ay);
HL.angDiff = (a, b) => {
  let d = (b - a) % HL.TAU;
  if (d > Math.PI) d -= HL.TAU;
  if (d < -Math.PI) d += HL.TAU;
  return d;
};
HL.approach = (v, t, d) => (v < t ? Math.min(v + d, t) : Math.max(v - d, t));

// Integer hash -> [0,1)
HL.hash = (x, y, s = 0) => {
  let h = Math.imul(x | 0, 374761393) ^ Math.imul(y | 0, 668265263) ^ Math.imul(s | 0, 982451653);
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  h ^= h >>> 16;
  return (h >>> 0) / 4294967296;
};
HL.vnoise = (x, y, s = 0) => {
  const xi = Math.floor(x), yi = Math.floor(y), xf = x - xi, yf = y - yi;
  const u = xf * xf * (3 - 2 * xf), v = yf * yf * (3 - 2 * yf);
  const a = HL.hash(xi, yi, s), b = HL.hash(xi + 1, yi, s), c = HL.hash(xi, yi + 1, s), d = HL.hash(xi + 1, yi + 1, s);
  return a + (b - a) * u + (c - a) * v + (a - b - c + d) * u * v;
};
HL.fbm = (x, y, s = 0, oct = 3) => {
  let t = 0, amp = 0.5, f = 1, n = 0;
  for (let i = 0; i < oct; i++) { t += amp * HL.vnoise(x * f, y * f, s + i * 17); n += amp; amp *= 0.5; f *= 2; }
  return t / n;
};
HL.rng = (seed) => {
  let s = (seed >>> 0) || 1;
  return () => { s ^= s << 13; s >>>= 0; s ^= s >>> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; };
};
// 4x4 ordered dither thresholds (the halftone look of the reference)
HL.BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5].map((v) => (v + 0.5) / 16);
HL.bayer = (x, y) => HL.BAYER[(y & 3) * 4 + (x & 3)];

HL.rgb = (hex) => { const n = parseInt(hex.slice(1), 16); return [(n >> 16) & 255, (n >> 8) & 255, n & 255]; };
HL.canvas = (w, h) => {
  const c = document.createElement('canvas');
  c.width = Math.max(1, w | 0); c.height = Math.max(1, h | 0);
  const g = c.getContext('2d');
  g.imageSmoothingEnabled = false;
  c.g = g;
  return c;
};

