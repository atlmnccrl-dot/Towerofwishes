# Builds js/i18n_<code>.js from tools_lang/keys.json (the English strings, harvested by test/strings.js) and
# tools_lang/<code>.txt (one translation per line, in the same order; "@N" lines are checkpoints: the next line is
# key N). Item-name parts and word order per language are below. Usage: python3 vesper/tools_lang/build.py [code ...]
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); JS = os.path.join(HERE, '..', 'js')
KEYS = json.load(open(os.path.join(HERE, 'keys.json')))
SUF_EN = ['of Edges', 'of the Wall', 'of Warding', 'of the Moon', 'of Thirst', 'of Haste', 'of Wind', 'of Patience', 'of Mending', 'of Fortune']
TIER_EN = ['Iron', 'Steel', 'Moonsteel', 'Bloodsteel', 'Bone', 'Silver', 'Moon', 'Blood']
BASE_EN = ['Blade', 'Saber', 'Axe', 'Spear', 'Greatsword', 'Coat', 'Mail', 'Plate', 'Cloak', 'Locket', 'Ring', 'Fang', 'Talisman']
ITEMS = {
  'es': dict(tier=['hierro', 'acero', 'acero lunar', 'acero sangriento', 'hueso', 'plata', 'luna', 'sangre'],
             base=['Hoja', 'Sable', 'Hacha', 'Lanza', 'Mandoble', 'Casaca', 'Cota', 'Coraza', 'Capa', 'Relicario', 'Anillo', 'Colmillo', 'Talismán'],
             suf=['de los Filos', 'del Muro', 'de la Guarda', 'de la Luna', 'de la Sed', 'de la Prisa', 'del Viento', 'de la Paciencia', 'de la Curación', 'de la Fortuna'],
             make="(b, t, s) => b + ' de ' + t + (s.length ? ' ' + s.join(' y ') : '')"),
  'pt': dict(tier=['ferro', 'aço', 'aço lunar', 'aço sangrento', 'osso', 'prata', 'lua', 'sangue'],
             base=['Lâmina', 'Sabre', 'Machado', 'Lança', 'Montante', 'Casaco', 'Cota', 'Couraça', 'Capa', 'Medalhão', 'Anel', 'Presa', 'Talismã'],
             suf=['dos Gumes', 'da Muralha', 'da Proteção', 'da Lua', 'da Sede', 'da Pressa', 'do Vento', 'da Paciência', 'da Cura', 'da Fortuna'],
             make="(b, t, s) => b + ' de ' + t + (s.length ? ' ' + s.join(' e ') : '')"),
  'fr': dict(tier=['fer', 'acier', 'acier lunaire', 'acier sanglant', 'os', 'argent', 'lune', 'sang'],
             base=['Lame', 'Sabre', 'Hache', 'Lance', 'Espadon', 'Veste', 'Cotte', 'Cuirasse', 'Cape', 'Médaillon', 'Anneau', 'Croc', 'Talisman'],
             suf=['des Tranchants', 'du Rempart', 'de la Garde', 'de la Lune', 'de la Soif', 'de la Hâte', 'du Vent', 'de la Patience', 'de la Guérison', 'de la Fortune'],
             make="(b, t, s) => b + (/^[aeiouh]/.test(t) ? \" d'\" : ' de ') + t + (s.length ? ' ' + s.join(' et ') : '')"),
  'de': dict(tier=['Eisen', 'Stahl', 'Mondstahl', 'Blutstahl', 'Knochen', 'Silber', 'Mond', 'Blut'],
             base=['Klinge', 'Säbel', 'Axt', 'Speer', 'Großschwert', 'Mantel', 'Kettenhemd', 'Plattenpanzer', 'Umhang', 'Medaillon', 'Ring', 'Fangzahn', 'Talisman'],
             suf=['der Schneiden', 'des Walls', 'des Schutzes', 'des Mondes', 'des Durstes', 'der Eile', 'des Windes', 'der Geduld', 'der Heilung', 'des Glücks'],
             make="(b, t, s) => t + b.toLowerCase() + (s.length ? ' ' + s.join(' und ') : '')"),
}
def build(code):
    lines = [l.rstrip('\n') for l in open(os.path.join(HERE, code + '.txt'), encoding='utf-8')]
    out, bad = [], []
    for l in lines:
        if l.startswith('@'):
            n = int(l[1:])
            if n != len(out): bad.append(f'checkpoint @{n} but at line {len(out)} ({KEYS[len(out)] if len(out) < len(KEYS) else "end"!r})')
            continue
        if l == '' and not out: continue
        out.append(l)
    if len(out) != len(KEYS): bad.append(f'{len(out)} lines for {len(KEYS)} keys')
    if bad: print(code, 'FAILED:', *bad, sep='\n  '); return False
    for k, v in zip(KEYS, out):
        if k.count('#') != v.count('#'): print(code, 'numbers differ:', repr(k), '->', repr(v)); return False
    d = {k: v for k, v in zip(KEYS, out) if v and v != k}
    it = ITEMS[code]
    items = '{ tier: %s, base: %s, suf: %s, make: %s }' % (json.dumps(dict(zip(TIER_EN, it['tier'])), ensure_ascii=False), json.dumps(dict(zip(BASE_EN, it['base'])), ensure_ascii=False), json.dumps(dict(zip(SUF_EN, it['suf'])), ensure_ascii=False), it['make'])
    js = ('// Generated by tools_lang/build.py from tools_lang/%s.txt: edit that file, not this one.\n' % code +
          'VS.I18N.add(%s, %s,\n  %s);\n' % (json.dumps(code), json.dumps(d, ensure_ascii=False, indent=0), items))
    open(os.path.join(JS, 'i18n_%s.js' % code), 'w', encoding='utf-8').write(js)
    print(code, len(d), 'strings')
    return True
codes = sys.argv[1:] or [c for c in ITEMS if os.path.exists(os.path.join(HERE, c + '.txt'))]
ok = all([build(c) for c in codes]); sys.exit(0 if ok else 1)
