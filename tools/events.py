#!/usr/bin/env python3
"""Build docs/EVENTS.md (the TW-001..430 ledger) from the master handoff.

Implementation state per event lives in tools/event_state.json ({"TW-001": ["Playable", "where"]}).
States: Not started, In progress, Playable, Cinematic done, Tested. Unlisted ids are Not started.
Run: python3 tools/events.py
"""
import json, re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'docs/source/MASTER_HANDOFF_2026-10-17.txt'), encoding='utf-8').read()
state = json.load(open(os.path.join(ROOT, 'tools/event_state.json')))
section, rows, events = None, [], []
lines = src.splitlines()
i = 0
while i < len(lines):
    l = lines[i]
    m = re.match(r'^(\d\d[ABC]?) — (.+)$', l.strip())
    if m and int(m.group(1)[:2]) <= 20 and 'inventory' not in l.lower():
        section = m.group(1) + ' — ' + m.group(2)
    m = re.match(r'^(TW-\d{3}) \[([A-Z]+)\]\s+(.+?)\s+·\s+(.+)$', l.strip())
    if m:
        eid, lab, title, kind = m.groups()
        desc = []
        j = i + 1
        while j < len(lines) and lines[j].strip() and not re.match(r'^TW-\d{3}', lines[j].strip()) and 'TOWER OF WISHES' not in lines[j]:
            desc.append(lines[j].strip()); j += 1
        events.append((section, eid, lab, title.strip(), kind.strip(), ' '.join(desc)))
    i += 1
assert len(events) == 430, len(events)
assert len({e[1] for e in events}) == 430
out = ['# Story event ledger (TW-001 – TW-430)', '',
       'Generated by `tools/events.py` from `docs/source/MASTER_HANDOFF_2026-10-17.txt`; implementation state from `tools/event_state.json`.',
       'Label = canon status (CANON, GAME, OPTION, OPEN). State = what the build actually does: Not started, In progress, Playable, Cinematic done, Tested.',
       '']
counts = {}
cur = None
for sec, eid, lab, title, kind, desc in events:
    if sec != cur:
        cur = sec
        out += ['', '## ' + sec, '', '| Id | Label | Event | Type | State | Where in the build |', '|---|---|---|---|---|---|']
    st, where = state.get(eid, ['Not started', ''])
    counts[st] = counts.get(st, 0) + 1
    out.append(f'| {eid} | {lab} | {title} | {kind} | {st} | {where} |')
summ = ['', '## Totals', ''] + [f'- {k}: {v}' for k, v in sorted(counts.items())]
open(os.path.join(ROOT, 'docs/EVENTS.md'), 'w', encoding='utf-8').write('\n'.join(out[:5] + summ + out[5:]) + '\n')
print('ledger:', counts)
